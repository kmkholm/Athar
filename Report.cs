using System;
using System.Linq;
using System.Text;

namespace Athar
{
    public static class Report
    {
        const string Css = "body{font-family:'Segoe UI',Tahoma,Arial,sans-serif;color:#1F2933;margin:32px auto;max-width:1100px;padding:0 24px;line-height:1.55}" +
            "h1{font-size:24px;margin:0 0 4px}h2{font-size:17px;margin:28px 0 10px;padding-bottom:6px;border-bottom:2px solid #1565C0}" +
            ".meta{color:#66788A;font-size:13px}table{border-collapse:collapse;width:100%;font-size:12.5px;margin:6px 0 14px}th{background:#F4F6F8;text-align:start;padding:7px 9px;border-bottom:1px solid #C5CDD6}" +
            "td{padding:6px 9px;border-bottom:1px solid #EDF0F3;vertical-align:top}.c{font-family:Consolas,monospace;direction:ltr;unicode-bidi:embed;word-break:break-all}.n{text-align:end;direction:ltr;white-space:nowrap}" +
            ".box{border:1px solid #DDE2E8;border-radius:6px;padding:14px;background:#F9FAFB;overflow:auto}.note{background:#FFF4E0;border-radius:5px;padding:10px 14px;font-size:13px;margin:8px 0}" +
            ".tag{display:inline-block;border-radius:10px;padding:1px 9px;font-size:11.5px;background:#E3EEFB;color:#0D47A1;margin-inline-end:4px}@media print{body{margin:10mm}h2{break-after:avoid}}";

        static string Page(string title, string body) =>
            $"<!doctype html><html lang='{(L.Ar ? "ar" : "en")}' dir='{(L.Ar ? "rtl" : "ltr")}'><head><meta charset='utf-8'><title>{Fmt.Html(title)}</title><style>{Css}</style></head><body>{body}" +
            $"<p class='meta' style='margin-top:30px'>{Fmt.Html(L.T("Generated by Athar"))} {App.Version} · {DateTime.UtcNow:yyyy-MM-dd HH:mm} UTC · {Fmt.Html(L.T("Developed by Dr. Mohammed Tawfik"))}</p></body></html>";

        static string AddrCell(string a) { var l = Labels.Find(a); if (a != Addr.Bare(a)) return "<span class='tag'>" + Fmt.Html(Bridges.NameOf(a.Substring(0, a.IndexOf(':')))) + "</span>" + AddrCell(Addr.Bare(a)); return (l != null && l.Name != "" ? "<b>" + Fmt.Html(l.Name) + "</b><br>" : "") + "<span class='c'>" + Fmt.Html(a) + "</span>"; }

        static string TraceBody(Graph g)
        {
            var chain = Chains.Get(g.Chain);
            var sb = new StringBuilder();
            sb.Append($"<p class='meta'>{Fmt.Html(L.T("Network"))}: {Fmt.Html(chain.Name)} · {Fmt.Html(L.T("Direction"))}: {Fmt.Html(L.T(g.Forward ? "Forward" : "Backward"))} · {Fmt.Html(L.T("Traced on"))}: {Fmt.Time(g.Created)} UTC<br>{Fmt.Html(L.T("Start address"))}: <span class='c'>{Fmt.Html(g.Start.Replace("\n", ", "))}</span><br>{Fmt.Html(L.T("Parameters"))}: <span class='c'>{Fmt.Html(g.Options)}</span></p>");
            sb.Append("<div class='box'>" + GraphGeo.Svg(g) + "</div>");
            sb.Append($"<h3>{Fmt.Html(L.T("Bubble map"))}</h3><div class='box'>" + GraphGeo.BubbleSvg(g) + "</div>");
            var ends = g.Nodes.Where(n => n.Depth > 0 && n.Stop != "").OrderBy(n => n.Stop == "service" ? 0 : 1).ThenBy(n => n.Depth).ToList();
            if (ends.Count > 0)
            {
                sb.Append($"<h3>{Fmt.Html(L.T("Where the trail ends"))}</h3><table><tr><th>{Fmt.Html(L.T("Address"))}</th><th>{Fmt.Html(L.T("Type"))}</th><th>{Fmt.Html(L.T("Hop"))}</th><th>{Fmt.Html(L.T("Amount"))}</th><th>{Fmt.Html(L.T("Why the trace stopped here"))}</th></tr>");
                foreach (var n in ends)
                    sb.Append($"<tr><td>{AddrCell(n.Id)}</td><td>{Fmt.Html(Ui.StatusName(g.Status(n)) + (n.Frozen != "" ? " · " + n.Frozen : ""))}</td><td class='n'>{n.Depth}</td><td class='n'>{Fmt.Html(string.Join(", ", g.Edges.Where(e => (g.Forward ? e.To : e.From) == n.Id).GroupBy(e => e.Asset).Select(x => Fmt.Amt(x.Sum(e => e.Amount)) + " " + x.Key)))}</td><td>{Fmt.Html(Ui.StopName(n.Stop))}</td></tr>");
                sb.Append("</table>");
            }
            sb.Append($"<h3>{Fmt.Html(L.T("All flows"))}</h3><table><tr><th>{Fmt.Html(L.T("From"))}</th><th>{Fmt.Html(L.T("To"))}</th><th>{Fmt.Html(L.T("Amount"))}</th><th>{Fmt.Html(L.T("Transfers"))}</th><th>{Fmt.Html(L.T("First (UTC)"))}</th><th>{Fmt.Html(L.T("Largest transaction"))}</th></tr>");
            foreach (var e in g.Edges.OrderBy(e => g.Node(e.From)?.Depth ?? 0).ThenByDescending(e => e.Amount))
                sb.Append($"<tr><td>{AddrCell(e.From)}</td><td>{AddrCell(e.To)}</td><td class='n'><b>{Fmt.Amt(e.Amount)} {Fmt.Html(e.Asset)}</b></td><td class='n'>{e.Count}</td><td class='n'>{Fmt.Time(e.First)}</td><td class='c'>{Fmt.Html(e.Hashes.FirstOrDefault() ?? "")}</td></tr>");
            sb.Append("</table>");
            foreach (var note in g.Notes.Where(n => n != "limit" && n != "recent" && n != "nolabel" && n != "relaykey").Distinct().Take(8)) sb.Append($"<div class='note'>{Fmt.Html(note)}</div>");
            return sb.ToString();
        }

        static string Method() =>
            $"<h2>{Fmt.Html(L.T("Method and limits"))}</h2><p>{Fmt.Html(L.T("Data comes from public blockchain explorers at the time of the trace. At every hop the largest transfers made after the funds arrived are followed; tracing stops at known services, contracts and very active wallets. Labels come from the explorer, a built-in list and the examiner's own labels."))}</p>" +
            $"<div class='note'>{Fmt.Html(L.T("A trace shows where value moved, not who owns the addresses. After the first hops an address may mix the traced funds with unrelated money. Confirm every key step on the explorer before relying on it."))}</div>" +
            $"<p class='meta'>{Fmt.Html(L.T("Data sources"))}: {Fmt.Html(string.Join(", ", Http.Sources.Keys.OrderBy(x => x).DefaultIfEmpty("—")))}</p>";

        public static string TraceHtml(Graph g, string lang)
        {
            string title = L.T("Fund-flow trace report");
            return Page(title, $"<h1>{Fmt.Html(title)}</h1>" + (Store.S.Examiner != "" ? $"<p class='meta'>{Fmt.Html(L.T("Examiner"))}: {Fmt.Html(Store.S.Examiner)}</p>" : "") + TraceBody(g) + Method());
        }

        public static string CaseHtml(CaseFile c, string lang)
        {
            var sb = new StringBuilder();
            sb.Append($"<h1>{Fmt.Html(c.Name)}</h1><p class='meta'>{Fmt.Html(L.T("Case report"))} · {Fmt.Html(L.T("Opened"))}: {Fmt.Day(c.Created)}" + (Store.S.Examiner != "" ? $" · {Fmt.Html(L.T("Examiner"))}: {Fmt.Html(Store.S.Examiner)}" : "") + "</p>");
            if (!string.IsNullOrWhiteSpace(c.Notes)) sb.Append($"<h2>{Fmt.Html(L.T("Summary"))}</h2><p>{Fmt.Html(c.Notes).Replace("\n", "<br>")}</p>");
            if (c.Findings.Count > 0)
            {
                sb.Append($"<h2>{Fmt.Html(L.T("Findings"))}</h2><ol>");
                foreach (var f in c.Findings) sb.Append($"<li>{Fmt.Html(f)}</li>");
                sb.Append("</ol>");
            }
            if (c.Items.Count > 0)
            {
                sb.Append($"<h2>{Fmt.Html(L.T("Addresses and transactions"))}</h2><table><tr><th>#</th><th>{Fmt.Html(L.T("Network"))}</th><th>{Fmt.Html(L.T("Item"))}</th><th>{Fmt.Html(L.T("Role"))}</th><th>{Fmt.Html(L.T("Note"))}</th></tr>");
                int i = 1;
                foreach (var it in c.Items)
                    sb.Append($"<tr><td>{i++}</td><td>{Fmt.Html(Chains.All.FirstOrDefault(x => x.Key == it.Chain)?.Name ?? it.Chain)}</td><td>{(it.Kind == "address" ? AddrCell(it.Value) : "<span class='c'>" + Fmt.Html(it.Value) + "</span>")}</td><td>{Fmt.Html(it.Role)}</td><td>{Fmt.Html(it.Note)}</td></tr>");
                sb.Append("</table>");
            }
            int t = 1;
            foreach (var g in c.Traces) { sb.Append($"<h2>{Fmt.Html(L.T("Trace"))} {t++}: {Fmt.Html(L.T(g.Forward ? "Where the money went" : "Where the money came from"))}</h2>"); sb.Append(TraceBody(g)); }
            sb.Append(Method());
            return Page(c.Name, sb.ToString());
        }

        public static string EdgesCsv(Graph g)
        {
            var sb = new StringBuilder("from,from_label,to,to_label,amount,asset,token_contract,transfers,first_utc,last_utc,largest_tx\n");
            foreach (var e in g.Edges) sb.AppendLine(string.Join(",", e.From, Fmt.Csv(Labels.Find(e.From)?.Name), e.To, Fmt.Csv(Labels.Find(e.To)?.Name), Fmt.Num(e.Amount), Fmt.Csv(e.Asset), e.Contract, e.Count, Fmt.Time(e.First), Fmt.Time(e.Last), e.Hashes.FirstOrDefault()));
            return sb.ToString();
        }
    }
}
